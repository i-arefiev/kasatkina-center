<script>
    document.addEventListener('DOMContentLoaded', function() {
        const triggers = document.querySelectorAll('.js-license-trigger');
        const modal = document.getElementById('license-modal');
        const closeBtn = document.getElementById('modal-close');
        const title = document.getElementById('modal-title');
        const date = document.getElementById('modal-date');
        const org = document.getElementById('modal-org');

        if (modal && triggers.length) {
            triggers.forEach(btn => {
                btn.addEventListener('click', function() {
                    title.textContent = this.dataset.title;
                    date.textContent = this.dataset.date;
                    org.textContent = this.dataset.org;
                    modal.classList.remove('hidden');
                    modal.classList.add('flex');
                });
            });

            function closeModal() {
                modal.classList.remove('flex');
                modal.classList.add('hidden');
            }

            closeBtn.addEventListener('click', closeModal);
            modal.addEventListener('click', function(e) {
                if (e.target === modal) closeModal();
            });
        }
    });
</script>